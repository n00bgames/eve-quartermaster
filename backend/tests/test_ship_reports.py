def generate(ships,**body):
    response=ships.env.client.post('/api/ship-reports',json=body)
    assert response.status_code==201,response.text
    return response.json()


def test_ship_counts_are_units_not_stacks_and_only_hulls(ships):
    report=generate(ships)
    assert report['report_kind']=='ships' and report['is_private'] and report['share_url'] is None
    assert report['summary']=={'ships':7,'ship_types':2,'asset_stacks':4}
    assert {r['item']:r['quantity'] for r in report['totals']}=={'Raven':4,'Atron':3}
    assert {r['ship_class'] for r in report['stock']}=={'Battleship','Frigate'}
    assert {r['owner'] for r in report['stock']}=={ships.char.name}
    assert all(row['location']==ships.station.name for row in report['stock'])
    assert not report['jobs'] and not report['blueprints'] and not report['pi']


def test_ship_report_is_creator_only_and_kind_isolated(ships):
    report=generate(ships);token=report['token']
    for path in ('/ship-reports/public/','/inventory-reports/reports/','/industry-reports/reports/','/industry-reports/public/'):
        assert ships.env.client.get('/api'+path+token).status_code==404
    for role in ('other','director','admin'):
        ships.env.current[0]=ships.env.users[role]
        assert ships.env.client.get('/api/ship-reports/reports/'+token).status_code==404
        assert ships.env.client.get('/api/ship-reports/reports/'+token+'/export/csv').status_code==404
        assert token not in str(ships.env.client.get('/api/ship-reports/reports').json())
    ships.env.current[0]=None
    assert ships.env.client.get('/api/ship-reports/reports/'+token).status_code==401


def test_ship_csv_and_pdf_have_total_and_per_type_quantities(ships):
    report=generate(ships);base='/api/ship-reports/reports/'+report['token']+'/export/'
    csv=ships.env.client.get(base+'csv')
    assert csv.status_code==200 and 'SHIP REPORT,TOTAL SHIPS,7,SHIP TYPES,2' in csv.text
    assert 'Raven,4' in csv.text and 'Atron,3' in csv.text
    assert 'Private Laser' not in csv.text and 'Mechanical Parts' not in csv.text
    pdf=ships.env.client.get(base+'pdf')
    assert pdf.status_code==200 and pdf.content.startswith(b'%PDF')
    text='\n'.join(page.extract_text() for page in PdfReader(BytesIO(pdf.content)).pages)
    assert all(word in text for word in ('Ship Report','Total ships: 7','Ship types: 2','Raven','Atron','Ships by type','Generated by EVE Quartermaster v2.0.0'))


def test_ship_generation_rejects_public_and_enforces_permissions(ships):
    assert ships.env.client.post('/api/ship-reports',json={'is_private':False}).status_code==422
    user=ships.env.users['member']
    permission=UserSectionPermission(user_id=user.id,section='ship_reports',can_view=False)
    ships.db.add(permission);ships.db.commit()
    assert ships.env.client.post('/api/ship-reports',json={}).status_code==403
    permission.can_view=True
    ships.db.add(UserSectionPermission(user_id=user.id,section='inventory_reports',can_view=False));ships.db.commit()
    assert ships.env.client.post('/api/ship-reports',json={}).status_code==403
    ships.env.current[0]=ships.env.users['quartermaster']
    assert ships.env.client.get('/api/ship-reports/context').status_code==403


def test_delete_and_expiry_never_affect_inventory_reports(ships):
    inventory=create(ships,path='/inventory-reports');report=generate(ships)
    row=ships.db.get(LocalScanReport,report['token']);row.expires_at=lifecycle.now()-timedelta(seconds=1);ships.db.commit()
    assert ships.env.client.get('/api/ship-reports/reports/'+report['token']).status_code==404
    current=generate(ships)
    deleted=ships.env.client.post('/api/ship-reports/reports/delete',json={'all_in_scope':True})
    assert deleted.status_code==200 and deleted.json()['deleted']==2
    assert ships.env.client.get('/api/ship-reports/reports/'+current['token']).status_code==404
    assert ships.env.client.get('/api/inventory-reports/reports/'+inventory['token']).status_code==200


def test_ship_permissions_rechecked_after_build(ships):
    from app.services import industry_reports as service
    original=service.build_ships
    def revoke(*args):
        result=original(*args)
        ships.db.add(UserSectionPermission(user_id=ships.env.users['member'].id,section='ship_reports',can_view=False));ships.db.commit()
        return result
    with patch.object(service,'build_ships',side_effect=revoke):
        assert ships.env.client.post('/api/ship-reports',json={}).status_code==403
    assert ships.db.scalar(select(LocalScanReport).where(LocalScanReport.report_kind=='ships')) is None


def test_ship_export_rechecks_permissions_after_rendering(ships):
    from app.services import industry_reports as service
    report=generate(ships)
    def revoke(data):
        ships.db.add(UserSectionPermission(user_id=ships.env.users['member'].id,section='ship_reports',can_view=False));ships.db.commit()
