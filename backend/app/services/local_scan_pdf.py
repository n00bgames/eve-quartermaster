"""Server-rendered, two-column PDF from an immutable public scan snapshot."""
from __future__ import annotations

import asyncio
from io import BytesIO
from pathlib import Path
from xml.sax.saxutils import escape
import httpx


async def logo_images(snapshot):
    # Fixed EVE Image Server URLs only, bounded requests/bytes/time; never fetch user URLs.
    keys = sorted({(kind, p[key]) for p in snapshot["pilots"] for kind, key in
                   (("corporations", "corporation_id"), ("alliances", "alliance_id")) if p[key]})[:64]
    images = {}
    slots = asyncio.Semaphore(4)
    async with httpx.AsyncClient(timeout=2, follow_redirects=False) as client:
        async def fetch(kind, eid):
            async with slots:
                try:
                    async with client.stream("GET", f"https://images.evetech.net/{kind}/{int(eid)}/logo?size=32") as response:
                        response.raise_for_status()
                        chunks = bytearray()
                        async for chunk in response.aiter_bytes():
                            chunks.extend(chunk)
                            if len(chunks) > 131072:
                                return
                        from PIL import Image
                        image = Image.open(BytesIO(chunks))
                        if image.width <= 128 and image.height <= 128:
                            image.load()
                            images[(kind, eid)] = bytes(chunks)
                except (httpx.HTTPError, ValueError, OSError):
                    pass  # Text/counts remain complete when logos are unavailable.
        try:
            await asyncio.wait_for(asyncio.gather(*(fetch(*key) for key in keys)), timeout=6)
        except asyncio.TimeoutError:
            pass
    return images


def render_pdf(snapshot, logos):
    from reportlab import rl_config
    from reportlab.lib import colors
    from reportlab.lib.enums import TA_LEFT
    from reportlab.lib.styles import ParagraphStyle
    from reportlab.lib.utils import ImageReader
    from reportlab.pdfbase import pdfmetrics
    from reportlab.pdfbase.ttfonts import TTFont
    from reportlab.platypus import BaseDocTemplate, Frame, PageTemplate, Paragraph, Table, TableStyle, Image, Spacer, BalancedColumns
    from reportlab.lib.pagesizes import A4

    # ReportLab ships these embeddable fonts; PDF output does not rely on host fonts.
    font_dir = Path(rl_config.__file__).parent / "fonts"
    for name, file in (("EQM", "Vera.ttf"), ("EQMBold", "VeraBd.ttf")):
        if name not in pdfmetrics.getRegisteredFontNames():
            pdfmetrics.registerFont(TTFont(name, str(font_dir / file)))
    stream = BytesIO()
    width, height = A4
    margin, gap = 34, 18
    column = (width - margin * 2 - gap) / 2
    doc = BaseDocTemplate(stream, pagesize=A4, leftMargin=margin, rightMargin=margin,
                          topMargin=108, bottomMargin=36, title="EVE Quartermaster - Local scan",
                          author=snapshot["account_name"])
    red = colors.HexColor("#a52632")
    style = ParagraphStyle("scan", fontName="EQM", fontSize=8, leading=11, textColor=colors.HexColor("#293243"), alignment=TA_LEFT)
    group_style = ParagraphStyle("group", parent=style, fontName="EQMBold", fontSize=10, leading=13)
    note_style = ParagraphStyle("note", parent=style, fontSize=7, leading=10, textColor=colors.HexColor("#586477"))

    def header(canvas, document):
        canvas.setFillColor(colors.HexColor("#172336"))
        canvas.rect(0, height - 92, width, 92, fill=1, stroke=0)
        logo = Path(__file__).resolve().parents[1] / "assets" / "eqm-logo.png"
        if logo.exists():
            canvas.drawImage(ImageReader(str(logo)), margin, height - 42, width=26, height=26, preserveAspectRatio=True, mask="auto")
        canvas.setFillColor(colors.white)
        canvas.setFont("EQMBold", 14)
        canvas.drawString(margin + 35, height - 29, "Local scan")
        attribution = f"Generated by EVE Quartermaster v{snapshot['application_version']} by {snapshot['account_name']}"
        # Account names can be 120 characters; wrap the complete attribution.
        attribution_p = Paragraph(escape(attribution), ParagraphStyle("attribution", parent=note_style, textColor=colors.white, fontSize=7, leading=9))
        _, ah = attribution_p.wrap(width - margin * 2, 30)
        attribution_p.drawOn(canvas, margin, height - 49 - ah)
        canvas.setFont("EQM", 7)
        canvas.drawString(margin, height - 79, f"{snapshot['character_count']} characters / {snapshot['input_count']} names | {snapshot['created_at'][:19].replace('T', ' ')} UTC")
        canvas.setFillColor(colors.HexColor("#586477"))
        canvas.drawString(margin, 20, "Public ESI snapshot | Red / marked = creator's highlighted organization")
        canvas.drawRightString(width - margin, 20, f"Page {document.page}")

    frames = [Frame(margin, 36, width - margin * 2, height - 144, id="scan-content", leftPadding=0, rightPadding=0, topPadding=0, bottomPadding=0)]
    doc.addPageTemplates(PageTemplate(id="scan", frames=frames, onPage=header))
    story = []
    story.append(Paragraph(escape(f"System: {(snapshot.get('system') or {}).get('name', 'Not specified')}"), group_style))
    story.append(Spacer(1, 8))
    for warning in snapshot["warnings"]:
        story.append(Paragraph(escape(warning), note_style))
        story.append(Spacer(1, 5))
    groups = {}
    for pilot in snapshot["pilots"]:
        key = pilot["alliance_id"] if pilot["affiliation_available"] else "unknown"
        groups.setdefault(key, []).append(pilot)

    def org_row(kind, eid, name, count, marked, bold=False):
        icon = Image(BytesIO(logos[(kind, eid)]), width=16, height=16) if (kind, eid) in logos else ""
        color = red if marked else colors.HexColor("#293243")
        s = ParagraphStyle("org", parent=group_style if bold else style, textColor=color)
        row = Table([[icon, Paragraph(escape(name) + (" [marked]" if marked else ""), s), str(count)]], colWidths=[21, column - 48, 27])
        row.setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "TOP"), ("LEFTPADDING", (0, 0), (-1, -1), 0),
                                ("RIGHTPADDING", (0, 0), (-1, -1), 3), ("FONTNAME", (2, 0), (2, 0), "EQMBold"),
                                ("FONTSIZE", (2, 0), (2, 0), 8), ("TEXTCOLOR", (2, 0), (2, 0), color), ("ALIGN", (2, 0), (2, 0), "RIGHT")]))
        return row

    for aid, pilots in sorted(groups.items(), key=lambda g: (-len(g[1]), str(g[0]))):
        name = "Affiliation unavailable" if aid == "unknown" else pilots[0]["alliance_name"] or "No alliance"
        story.append(Spacer(1, 8))
        heading = org_row("alliances", aid, name, len(pilots), any(p.get("alliance_highlighted") for p in pilots), True)
        heading.keepWithNext = True
        story.append(heading)
        corps = {}
        for pilot in pilots:
            corps.setdefault(pilot["corporation_id"], []).append(pilot)
        for cid, members in sorted(corps.items(), key=lambda c: (-len(c[1]), c[1][0]["corporation_name"].casefold())):
            heading = org_row("corporations", cid, members[0]["corporation_name"], len(members), any(p.get("highlighted") for p in members))
            heading.keepWithNext = True
            story.append(heading)
            story.append(Paragraph(escape(members[0]["name"]), style))
            for offset in range(1, len(members), 6):
                story.append(Paragraph(escape(", ".join(p["name"] for p in members[offset:offset + 6])), style))
            story.append(Spacer(1, 5))
    if snapshot["unresolved"]:
        story.append(Paragraph(f"Unresolved names ({len(snapshot['unresolved'])})", group_style))
        for name in snapshot["unresolved"]:
            story.append(Paragraph(escape(name), style))
    story.append(Spacer(1, 10))
    story.append(Paragraph(escape(snapshot["source"]), note_style))
    expiry = snapshot["expires_at"] or "Permanent (until deleted)"
    story.append(Paragraph(escape(f"Report retention: {expiry}"), note_style))
    doc.build([BalancedColumns(story, nCols=2, innerPadding=gap, leftPadding=0, rightPadding=0)])
    return stream.getvalue()
