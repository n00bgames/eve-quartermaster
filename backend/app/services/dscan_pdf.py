"""Paginated directional-scan report with observed/manual counts and linked local."""
from io import BytesIO
from pathlib import Path
from xml.sax.saxutils import escape
import asyncio
import httpx
from app.services.local_scan_pdf import logo_images


async def report_images(snapshot):
    images = await logo_images(snapshot.get("local_scan") or {"pilots": []})
    keys = [r["type_id"] for r in snapshot["rows"] if r["type_id"] and r["category"] in {"ships", "deployables"}][:48]
    semaphore = asyncio.Semaphore(4)
    async with httpx.AsyncClient(timeout=2, follow_redirects=False) as client:
        async def fetch(eid):
            async with semaphore:
                try:
                    async with client.stream("GET", f"https://images.evetech.net/types/{int(eid)}/icon?size=32") as response:
                        response.raise_for_status()
                        data = bytearray()
                        async for chunk in response.aiter_bytes():
                            data.extend(chunk)
                            if len(data) > 131072:
                                return
                        from PIL import Image
                        icon = Image.open(BytesIO(data))
                        if icon.width <= 128 and icon.height <= 128:
                            icon.load()
                            images[("types", eid)] = bytes(data)
                except (httpx.HTTPError, ValueError, OSError):
                    pass
        try:
            await asyncio.wait_for(asyncio.gather(*(fetch(key) for key in set(keys))), timeout=6)
        except asyncio.TimeoutError:
            pass
    return images


def render_pdf(snapshot, images):
    from reportlab import rl_config
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle
    from reportlab.lib.utils import ImageReader
    from reportlab.pdfbase import pdfmetrics
    from reportlab.pdfbase.ttfonts import TTFont
    from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, Image
    for name, file in (("EQM", "Vera.ttf"), ("EQMBold", "VeraBd.ttf")):
        if name not in pdfmetrics.getRegisteredFontNames():
            pdfmetrics.registerFont(TTFont(name, str(Path(rl_config.__file__).parent / "fonts" / file)))
    stream = BytesIO()
    width, height = A4
    margin = 34
    content_width = width - 2 * margin
    base = ParagraphStyle("body", fontName="EQM", fontSize=8, leading=11, textColor=colors.HexColor("#263347"))
    title = ParagraphStyle("section", parent=base, fontName="EQMBold", fontSize=11, leading=15, spaceBefore=10, spaceAfter=6, keepWithNext=True)
    note = ParagraphStyle("note", parent=base, fontSize=7, leading=10, spaceAfter=4)
    red = ParagraphStyle("marked", parent=base, textColor=colors.HexColor("#b32337"))

    def p(text, style=base):
        return Paragraph(escape(str(text)), style)

    def header(canvas, doc):
        canvas.setFillColor(colors.HexColor("#172336"))
        canvas.rect(0, height - 124, width, 124, fill=1, stroke=0)
        logo = Path(__file__).resolve().parents[1] / "assets" / "eqm-logo.png"
        if logo.exists():
            canvas.drawImage(ImageReader(str(logo)), margin, height-43, width=26, height=26, preserveAspectRatio=True, mask="auto")
        canvas.setFillColor(colors.white); canvas.setFont("EQMBold", 14)
        canvas.drawString(margin+35, height-30, "Directional scan")
        canvas.setFont("EQMBold", 10)
        canvas.drawString(margin, height-49, f"System: {(snapshot.get('system') or {}).get('name', 'Not specified')}")
        canvas.drawRightString(width-margin, height-49, f"Total ships: {snapshot['ship_count']:,}")
        attribution = p(f"Generated by EVE Quartermaster v{snapshot['application_version']} by {snapshot['account_name']}",
                        ParagraphStyle("header", parent=note, textColor=colors.white))
        _, h = attribution.wrap(content_width, 30)
        attribution.drawOn(canvas, margin, height-63-h)
        canvas.setFont("EQM", 7)
        canvas.drawString(margin, height-111, snapshot["created_at"][:19].replace("T", " ") + " UTC")
        canvas.setFillColor(colors.HexColor("#586477")); canvas.setFont("EQM", 7)
        canvas.drawString(margin, 20, "SDE base hull mass | Manual ships are estimates | Red = marked linked-local pilots")
        canvas.drawRightString(width-margin, 20, f"Page {doc.page}")

    doc = SimpleDocTemplate(stream, pagesize=A4, leftMargin=margin, rightMargin=margin,
                            topMargin=140, bottomMargin=36, title="EVE Quartermaster - Directional scan", author=snapshot["account_name"])
    story = [p(f"{snapshot['object_count']:,} observed objects | {snapshot['observed_ship_count']:,} observed ships + {snapshot['manual_ship_count']:,} manual = {snapshot['ship_count']:,} ships"),
             p(f"{'Total' if snapshot['mass_complete'] else 'Known / partial'} base ship mass: {snapshot['ship_mass_kg']/1000:,.3f} t"),
             p(f"Retention: {snapshot['expires_at'] or 'Permanent until deleted'}", note)]
    for warning in snapshot["warnings"]:
        story.append(p(warning, note))

    def table(headers, rows, widths):
        t = Table([[p(h) for h in headers], *rows], colWidths=widths, repeatRows=1, hAlign="LEFT")
        t.setStyle(TableStyle([("BACKGROUND", (0,0), (-1,0), colors.HexColor("#e8edf4")),
                               ("VALIGN", (0,0), (-1,-1), "TOP"), ("BOTTOMPADDING", (0,0), (-1,-1), 5),
                               ("LINEBELOW", (0,0), (-1,-1), .3, colors.HexColor("#d9dfe8"))]))
        story.append(t)

    for category, heading in (("ships", "Ships"), ("deployables", "Deployables"), ("structures", "Structures"),
                               ("drones", "Drones and fighters"), ("other", "Other objects"), ("unresolved", "Unresolved types")):
        selected = [r for r in snapshot["rows"] if r["category"] == category]
        if not selected:
            continue
        story.append(p(heading, title))
        rows = []
        for row in selected:
            key = ("types", row["type_id"])
            icon = Image(BytesIO(images[key]), width=18, height=18) if key in images else ""
            rows.append([icon, p(row["type_name"]), p(row["group_name"]), p(row["observed"]), p(row["manual"]), p(row["count"])])
        table(["", "Type", "Class", "Seen", "Manual", "Total"], rows, [24, content_width-231, 92, 37, 42, 36])
    story.append(p("Ship classes", title))
    table(["Class", "Total"], [[p(r["name"]), p(r["count"])] for r in snapshot["classes"]], [content_width-65, 65])
    local = snapshot.get("local_scan")
    if local:
        story.append(p(f"Linked local scan (Total pilots: {local['input_count']:,})", title))
        story.append(p(f"{local['character_count']:,} resolved / {len(local['unresolved']):,} unresolved names", note))
        story.append(p("Local membership does not identify the owners of scanned ships.", note))
        orgs = {}
        for pilot in local["pilots"]:
            for kind, eid, name, marked in (
                ("alliances", pilot["alliance_id"], pilot.get("alliance_name") or ("No alliance" if pilot["affiliation_available"] else "Affiliation unavailable"), pilot.get("alliance_highlighted")),
                ("corporations", pilot["corporation_id"], pilot["corporation_name"], pilot.get("highlighted"))):
                key = (kind, eid, name)
                entry = orgs.setdefault(key, {"count": 0, "marked": False})
                entry["count"] += 1
                entry["marked"] |= bool(marked)
        for (kind, eid, name), summary in sorted(orgs.items(), key=lambda r: (r[0][0], -r[1]["count"], r[0][2])):
            icon = Image(BytesIO(images[(kind, eid)]), width=16, height=16) if (kind, eid) in images else ""
            style = red if summary["marked"] else base
            label = ("Alliance: " if kind == "alliances" else "Corporation: ") + name
            if summary["marked"]: label += " [marked]"
            row = Table([[icon, p(label, style), p(summary["count"], style)]], colWidths=[22, content_width-62, 40])
            row.setStyle(TableStyle([("VALIGN", (0,0), (-1,-1), "TOP")]))
            story.append(row)
        story.append(Spacer(1, 6))
        for pilot in local["pilots"]:
            style = red if pilot.get("highlighted") else base
            label = " [marked]" if pilot.get("highlighted") else ""
            orgs = f"{pilot['corporation_name']} / {pilot.get('alliance_name') or ('No alliance' if pilot['affiliation_available'] else 'Affiliation unavailable')}"
            icon_key = ("corporations", pilot["corporation_id"])
            icon = Image(BytesIO(images[icon_key]), width=16, height=16) if icon_key in images else ""
            row = Table([[icon, p(pilot["name"]+label+" - "+orgs, style)]], colWidths=[22, content_width-22])
            row.setStyle(TableStyle([("VALIGN", (0,0), (-1,-1), "TOP")]))
            story.append(row)
        for name in local["unresolved"]:
            story.append(p("Unresolved pilot: " + name, note))
        for warning in local["warnings"]:
            story.append(p(warning, note))
    if snapshot["ignored"]:
        story.append(p("Skipped input rows", title))
        for row in snapshot["ignored"]:
            story.append(p(f"Line {row['line']}: {row['reason']}", note))
    story.append(Spacer(1, 8)); story.append(p(snapshot["source"], note))
    doc.build(story, onFirstPage=header, onLaterPages=header)
    return stream.getvalue()
