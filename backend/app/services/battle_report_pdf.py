"""Branded export of a saved Battle Report, with privacy-safe creator attribution."""
from io import BytesIO
from pathlib import Path
from xml.sax.saxutils import escape

def render_pdf(data,creator,version,created_at):
    from reportlab.platypus import SimpleDocTemplate,Paragraph,Table,TableStyle,Spacer
    from reportlab.lib.styles import getSampleStyleSheet,ParagraphStyle
    from reportlab.lib.pagesizes import A4
    from reportlab.lib import colors
    from reportlab.lib.utils import ImageReader
    styles=getSampleStyleSheet();small=ParagraphStyle('small',parent=styles['Normal'],fontSize=7,leading=10)
    white=ParagraphStyle('white',parent=small,textColor=colors.white)
    def p(v):return Paragraph(escape(str(v if v is not None else '')),small)
    report=data['report'];stream=BytesIO();width,height=A4
    def header(canvas,doc):
        canvas.setFillColor(colors.HexColor('#172336'));canvas.rect(0,height-106,width,106,fill=1,stroke=0)
        logo=Path(__file__).resolve().parents[1]/'assets'/'eqm-logo.png'
        if logo.exists():canvas.drawImage(ImageReader(str(logo)),32,height-35,width=24,height=24,mask='auto')
        canvas.setFillColor(colors.white);canvas.setFont('Helvetica-Bold',14);canvas.drawString(65,height-28,'Battle Report')
        identity=Paragraph(escape(f'Generated by EVE Quartermaster v{version} by {creator}'),white)
        _,h=identity.wrap(width-64,35);identity.drawOn(canvas,32,height-40-h)
        canvas.setFont('Helvetica',8);canvas.drawString(32,height-81,'Generated '+created_at[:19].replace('T',' ')+' UTC')
        canvas.drawString(32,height-97,f"{report['pilot_count']} pilots | {report['killmail_count']} killmails")
        canvas.setFillColor(colors.HexColor('#586477'));canvas.setFont('Helvetica',7);canvas.drawRightString(width-32,20,f'Page {doc.page}')
    story=[Paragraph(' / '.join(s.get('system_name','Unknown') for s in report['systems']),styles['Heading2']),p(data.get('coverage',{}).get('warning','')),
        p(f"Engagement: {report['start_time']} to {report['end_time']}"),Spacer(1,10)]
    fields=['character_name','corporation_name','alliance_name','side','damage_done','damage_taken']
    story.append(Paragraph('Involved pilots',styles['Heading2']))
    rows=[[p(k.replace('_',' ').title()) for k in fields]]+[[p(row.get(k)) for k in fields] for row in report['participants']]
    table=Table(rows,repeatRows=1,colWidths=[(width-64)/len(fields)]*len(fields));table.setStyle(TableStyle([('VALIGN',(0,0),(-1,-1),'TOP'),('BACKGROUND',(0,0),(-1,0),colors.HexColor('#e8edf4')),('LINEBELOW',(0,0),(-1,-1),.3,colors.HexColor('#d9dfe8'))]));story.append(table)
    story.append(Paragraph('Timeline',styles['Heading2']))
    for row in report['timeline']:story.append(p(f"{row.get('killmail_time')} | {row.get('victim_name')} | {row.get('victim_ship_type_name')} | {row.get('system_name')}"))
    doc=SimpleDocTemplate(stream,pagesize=A4,leftMargin=32,rightMargin=32,topMargin=122,bottomMargin=32)
    doc.build(story,onFirstPage=header,onLaterPages=header)
    return stream.getvalue()
