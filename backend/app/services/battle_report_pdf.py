"""Saved battle export: teams, composition, participants and the full loss timeline."""
from io import BytesIO
from pathlib import Path
from xml.sax.saxutils import escape


def render_pdf(data, creator, version, created_at):
    from reportlab.platypus import SimpleDocTemplate, Paragraph, Table, TableStyle, Spacer, PageBreak
    from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
    from reportlab.lib.pagesizes import A4
    from reportlab.lib import colors
    from reportlab.lib.utils import ImageReader

    styles = getSampleStyleSheet()
    small = ParagraphStyle('battle-small', parent=styles['Normal'], fontSize=7.5, leading=10.5)
    white = ParagraphStyle('battle-white', parent=small, textColor=colors.white)
    heading = ParagraphStyle('battle-heading', parent=styles['Heading2'], fontSize=12, spaceBefore=12, spaceAfter=7)
    side_colors = ['#e5f3f7', '#fbe9e7', '#fcf2d7']
    report = data['report']
    stream = BytesIO()
    width, height = A4
    usable = width - 64

    def p(value, style=small):
        return Paragraph(escape(str(value if value is not None else 'Unknown')).replace('\n', '<br/>'), style)

    def number(value):
        return f'{value:,.0f}' if value is not None else 'Unknown'

    def isk(value):
        return number(value) + ' ISK' if value is not None else 'Unknown'

    def utc(value):
        return str(value or 'Unknown').replace('T', ' ').replace('+00:00', '').replace('Z', '')[:19] + ' UTC'

    def side(value):
        return {0: 'Team 1', 1: 'Team 2', 2: 'Third parties'}.get(value, 'Unassigned')

    def header(canvas, doc):
        canvas.setFillColor(colors.HexColor('#172336'))
        canvas.rect(0, height-104, width, 104, fill=1, stroke=0)
        logo = Path(__file__).resolve().parents[1] / 'assets' / 'eqm-logo.png'
        if logo.exists():
            canvas.drawImage(ImageReader(str(logo)), 32, height-35, width=24, height=24, mask='auto')
        canvas.setFillColor(colors.white)
        canvas.setFont('Helvetica-Bold', 15)
        canvas.drawString(65, height-28, 'Battle Report')
        identity = p(f'Generated by EVE Quartermaster v{version} by {creator}', white)
        _, h = identity.wrap(usable, 35)
        identity.drawOn(canvas, 32, height-40-h)
        canvas.setFont('Helvetica', 8)
        canvas.drawString(32, height-80, 'Generated ' + utc(created_at))
        canvas.drawString(32, height-95, f"{number(report.get('pilot_count'))} pilots | {number(report.get('killmail_count'))} killmails")
        canvas.setFillColor(colors.HexColor('#586477'))
        canvas.setFont('Helvetica', 7)
        canvas.drawString(32, 20, 'EVE Quartermaster | Saved battle snapshot')
        canvas.drawRightString(width-32, 20, f'Page {doc.page}')

    story = []

    def section(title, columns, rows, fractions, sides=None):
        # Heading is part of the repeated table header so it cannot be stranded on a prior page.
        title_style = ParagraphStyle('table-title', parent=heading, textColor=colors.white, spaceBefore=0, spaceAfter=0)
        content = [[p(title, title_style)] + ['']*(len(columns)-1), [p(c) for c in columns]]
        content.extend([[p(v) for v in row] for row in rows] or [[p('No records')] + ['']*(len(columns)-1)])
        table = Table(content, colWidths=[usable*f/sum(fractions) for f in fractions], repeatRows=2, splitInRow=1, hAlign='LEFT')
        rules = [('SPAN',(0,0),(-1,0)), ('BACKGROUND',(0,0),(-1,0),colors.HexColor('#24384f')),
            ('BACKGROUND',(0,1),(-1,1),colors.HexColor('#e8edf4')), ('VALIGN',(0,0),(-1,-1),'TOP'),
            ('LEFTPADDING',(0,0),(-1,-1),6), ('RIGHTPADDING',(0,0),(-1,-1),6),
            ('TOPPADDING',(0,0),(-1,-1),6), ('BOTTOMPADDING',(0,0),(-1,-1),6),
            ('LINEBELOW',(0,1),(-1,-1),.3,colors.HexColor('#d9dfe8'))]
        if sides:
            for i, value in enumerate(sides, 2):
                rules.append(('BACKGROUND',(0,i),(-1,i),colors.HexColor(side_colors[value if value in (0,1,2) else 2])))
        table.setStyle(TableStyle(rules))
        story.extend([table, Spacer(1, 12)])

    story.extend([Paragraph(escape(' / '.join(s.get('system_name','Unknown') for s in report.get('systems',[]))), heading),
        p(f"Selected pilot: {data.get('pilot',{}).get('name','Unknown')}"),
        p(f"Engagement: {utc(report.get('start_time'))} to {utc(report.get('end_time'))}"),
        p(f"Estimated destruction: {isk(report.get('estimated_total_value'))}; {number(report.get('unknown_value_killmails',0))} killmail values unknown."),
        Spacer(1,8), p(data.get('coverage',{}).get('warning','Coverage may be incomplete.')),
        p('Team assignments follow the saved classification, including manual changes. Third parties may be ambiguous; missing values are not zero-valued losses.'), Spacer(1,12)])
    teams = report.get('teams',[])
    section('Team summary', ['Team / organizations','Pilots','Ships lost','Known ISK lost','Damage','Efficiency'], [
        [side(t['side'])+' - '+t.get('label','')+'\n'+'\n'.join(f"{o['name']} ({o['pilot_count']} pilots)" for o in t.get('organizations',[])),
         number(t.get('pilot_count')), number(t.get('ships_lost')), isk(t.get('isk_lost'))+f"\n{t.get('unknown_value_losses',0)} unknown losses",
         number(t.get('damage_inflicted')), f"{t['efficiency']:.1f}%" if t.get('efficiency') is not None else 'Unknown'] for t in teams],
        [35,9,10,20,16,10], [t['side'] for t in teams])
    story.extend([p('Composition counts are observed pilot/hull combinations and appearances in retained killmails, not a simultaneous fleet census. A pilot using multiple hulls can appear in multiple rows.'), Spacer(1,8)])
    comp = sorted(report.get('composition',[]), key=lambda row:(row.get('side',2), -row.get('involved',0), row.get('ship_type_name','')))
    section('Ship composition', ['Team','Hull / class','Pilots','Appearances','Lost','Known loss value'], [
        [side(r.get('side')), r.get('ship_type_name','Unknown')+'\n'+(r.get('ship_group_name') or 'Unresolved class'),
         number(r.get('pilots')), number(r.get('involved')), number(r.get('lost')), isk(r.get('loss_value'))] for r in comp],
        [15,32,9,14,8,22], [r.get('side',2) for r in comp])
    story.append(PageBreak())
    pilots = sorted(report.get('participants',[]), key=lambda r:(r.get('side',2),-r.get('damage_done',0),r.get('character_name','')))
    section('Involved pilots and damage', ['Pilot / affiliations','Team','Observed hulls','Damage done / taken','Kills / final blows','Losses / known value'], [
        ['\n'.join(filter(None,[r.get('character_name','Unknown'),r.get('corporation_name'),r.get('alliance_name')])),
         side(r.get('side')), '\n'.join(r.get('ship_type_names',[])) or 'Unknown',
         number(r.get('damage_done'))+' / '+number(r.get('damage_taken')),
         number(r.get('killmail_participations'))+' / '+number(r.get('final_blows')),
         number(r.get('losses'))+' / '+isk(r.get('loss_value'))] for r in pilots],
        [27,13,20,14,12,14], [r.get('side',2) for r in pilots])
    timeline = report.get('timeline',[])
    section('Loss timeline', ['Time / system','Victim / hull','Team','Damage / attackers','Estimated value'], [
        [utc(r.get('killmail_time'))+'\n'+r.get('system_name','Unknown')+f"\nKillmail {r.get('killmail_id','?')}",
         r.get('victim_name','Unknown')+'\n'+r.get('victim_ship_type_name','Unknown'), side(r.get('victim_side')),
         number(r.get('damage_taken'))+' / '+number(r.get('attacker_count')), isk(r.get('estimated_total_value'))] for r in timeline],
        [26,30,14,14,16], [r.get('victim_side',2) for r in timeline])
    coverage = data.get('coverage',{})
    story.extend([p(coverage.get('grouping_rule','')),p(f"Canonical source: {coverage.get('canonical_source','ESI killmails')}. Discovery/value source: {coverage.get('discovery_source','zKillboard')}.")])
    doc = SimpleDocTemplate(stream, pagesize=A4, leftMargin=32, rightMargin=32, topMargin=120, bottomMargin=36,
        title='EVE Quartermaster Battle Report', author=creator)
    doc.build(story, onFirstPage=header, onLaterPages=header)
    return stream.getvalue()
